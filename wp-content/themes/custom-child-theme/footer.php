 document.addEventListener("DOMContentLoaded", function () {

    const impactSection = document.querySelector(".ukt-impact-story-section");
    const counters = document.querySelectorAll(".ukt-impact-story-number-item h3");

    let hasCounted = false;

    function animateCounter(counter) {

        const numberText = counter.textContent.trim();

        /* Remove comma and + */
        const target = parseInt(
            numberText.replace(/,/g, "").replace("+", ""),
            10
        );

        const duration = 2000;
        const startTime = performance.now();

        function updateCounter(currentTime) {

            const elapsed = currentTime - startTime;
            const progress = Math.min(elapsed / duration, 1);

            const currentNumber = Math.floor(
                progress * target
            );

            counter.innerHTML =
                currentNumber.toLocaleString("en-IN") +
                '<span>+</span>';

            if (progress < 1) {
                requestAnimationFrame(updateCounter);
            } else {
                counter.innerHTML =
                    target.toLocaleString("en-IN") +
                    '<span>+</span>';
            }
        }

        requestAnimationFrame(updateCounter);
    }


    const observer = new IntersectionObserver(
        function (entries) {

            entries.forEach(function (entry) {

                if (entry.isIntersecting && !hasCounted) {

                    hasCounted = true;

                    counters.forEach(function (counter, index) {

                        setTimeout(function () {
                            animateCounter(counter);
                        }, index * 150);

                    });

                }

            });

        },
        {
            threshold: 0.35
        }
    );


    if (impactSection) {
        observer.observe(impactSection);
    }

});
