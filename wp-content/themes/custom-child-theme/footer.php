    function openFlipbook(pdfUrl, bookTitle) {
        if (!pdfUrl) return;
        titleElem.textContent = bookTitle;
        dlBtn.href = pdfUrl;
        dlBtn.setAttribute("download", pdfUrl.split("/").pop());
        modal.classList.add("is-open");
        document.body.style.overflow = "hidden";
        loader.classList.add("is-active");
        currentZoom = 1;
        if (stage) stage.style.transform = `scale(1)`;

        renderedPagesCache = {};
        activeLeftPage = null;
        activeRightPage = 1;

        if (!window.pdfjsLib) {
            loader.classList.remove("is-active");
            window.open(pdfUrl, "_blank", "noopener");
            return;
        }

        pdfjsLib.getDocument(pdfUrl).promise.then(doc => {
            currentPdfDoc = doc;
            totalPages = doc.numPages;
            totalPagesElem.textContent = totalPages;
            slider.max = totalPages;
            slider.value = 1;

            renderSpread(1).then(() => {
                loader.classList.remove("is-active");
            });
        }).catch(err => {
            console.error("Error loading PDF document:", err);
            loader.classList.remove("is-active");
            window.open(pdfUrl, "_blank", "noopener");
        });
    }

    function closeFlipbook() {
        modal.classList.remove("is-open");
        document.body.style.overflow = "";
        currentPdfDoc = null;
        renderedPagesCache = {};
    }

    if (closeBtn) closeBtn.addEventListener("click", closeFlipbook);

    // Render single PDF page to canvas
    async function getPageCanvas(pageNum) {
        if (!pageNum || pageNum < 1 || pageNum > totalPages) return null;
        if (renderedPagesCache[pageNum]) return renderedPagesCache[pageNum];

        try {
            const page = await currentPdfDoc.getPage(pageNum);
            const viewport = page.getViewport({ scale: 1.5 });
            const canvas = document.createElement("canvas");
            const ctx = canvas.getContext("2d");
            canvas.width = viewport.width;
            canvas.height = viewport.height;

            await page.render({ canvasContext: ctx, viewport: viewport }).promise;
            renderedPagesCache[pageNum] = canvas;
            return canvas;
        } catch (e) {
            console.error("Page render error:", e);
            return null;
        }
    }

    // Draw cached canvas to target canvas
    function drawToCanvas(targetCanvas, sourceCanvas) {
        if (!targetCanvas) return;
        const ctx = targetCanvas.getContext("2d");
        if (!sourceCanvas) {
            targetCanvas.width = 450;
            targetCanvas.height = 636;
            ctx.fillStyle = "#faf9f6";
            ctx.fillRect(0, 0, targetCanvas.width, targetCanvas.height);
            return;
        }
        targetCanvas.width = sourceCanvas.width;
        targetCanvas.height = sourceCanvas.height;
        ctx.clearRect(0, 0, targetCanvas.width, targetCanvas.height);
        ctx.drawImage(sourceCanvas, 0, 0);
    }

    // Render Spread (Single Front Cover in Center, Open Spreads, Single Last Page in Center)
    async function renderSpread(page) {
        let leftPageNum = null;
        let rightPageNum = null;

        if (page <= 1) {
            leftPageNum = null;
            rightPageNum = 1;
            if (spreadElem) spreadElem.className = "ukt-flipbook-spread is-single-cover";
        } else if (page >= totalPages) {
            leftPageNum = totalPages;
            rightPageNum = null;
            if (spreadElem) spreadElem.className = "ukt-flipbook-spread is-single-last";
        } else {
            if (page % 2 === 0) {
                leftPageNum = page;
                rightPageNum = page + 1 < totalPages ? page + 1 : page + 1;
            } else {
                leftPageNum = page - 1;
                rightPageNum = page;
            }
            if (spreadElem) spreadElem.className = "ukt-flipbook-spread is-open-spread";
        }

        activeLeftPage = leftPageNum;
        activeRightPage = rightPageNum;

        const [leftCanvas, rightCanvas] = await Promise.all([
            getPageCanvas(leftPageNum),
            getPageCanvas(rightPageNum)
        ]);

        drawToCanvas(canvasLeft, leftCanvas);
        drawToCanvas(canvasRight, rightCanvas);

        if (pageNumLeft) pageNumLeft.textContent = leftPageNum ? `Page ${leftPageNum}` : "";
        if (pageNumRight) pageNumRight.textContent = rightPageNum ? `Page ${rightPageNum}` : "";

        if (currPageElem) {
            if (rightPageNum === 1 && leftPageNum === null) {
                currPageElem.textContent = "1 (Cover)";
            } else if (leftPageNum === totalPages && rightPageNum === null) {
                currPageElem.textContent = `${totalPages} (End)`;
            } else if (leftPageNum && rightPageNum) {
                currPageElem.textContent = `${leftPageNum}-${rightPageNum}`;
            } else {
                currPageElem.textContent = rightPageNum || leftPageNum || "1";
            }
        }

        if (slider) slider.value = rightPageNum || leftPageNum || 1;

        const isAtStart = (rightPageNum === 1 && leftPageNum === null);
        const isAtEnd = (leftPageNum === totalPages && rightPageNum === null);

        const canPrev = !isAtStart;
        const canNext = !isAtEnd;

        if (prevBtn) prevBtn.disabled = !canPrev;
        if (navPrevBtn) navPrevBtn.disabled = !canPrev;
        if (nextBtn) nextBtn.disabled = !canNext;
        if (navNextBtn) navNextBtn.disabled = !canNext;

        if (leafRight) leafRight.style.cursor = canNext ? "pointer" : "default";
        if (leafLeft) leafLeft.style.cursor = canPrev ? "pointer" : "default";
    }

    // 3D Animated Flip Forward
    async function flipNext() {
        if (isFlipping || !currentPdfDoc) return;
        if (activeLeftPage === totalPages && activeRightPage === null) return;

        let targetPage;
        if (activeRightPage === 1 && activeLeftPage === null) {
            targetPage = 2;
        } else {
            const nextStep = (activeLeftPage || activeRightPage) + 2;
            if (nextStep >= totalPages) {
                targetPage = totalPages;
            } else {
                targetPage = nextStep;
            }
        }

        isFlipping = true;

        const frontPageNum = activeRightPage;
        const backPageNum = targetPage;
        let nextUnderCanvasPage = null;

        if (targetPage >= totalPages) {
            nextUnderCanvasPage = null;
        } else {
            nextUnderCanvasPage = targetPage + 1 <= totalPages ? targetPage + 1 : null;
        }

        const [frontCanvas, backCanvas, nextRightCanvas] = await Promise.all([
            getPageCanvas(frontPageNum),
            getPageCanvas(backPageNum),
            getPageCanvas(nextUnderCanvasPage)
        ]);

        drawToCanvas(canvasAnimFront, frontCanvas);
        drawToCanvas(canvasAnimBack, backCanvas);
        drawToCanvas(canvasRight, nextRightCanvas);

        animLeaf.style.display = "block";
        animLeaf.classList.remove("flip-to-left");
        void animLeaf.offsetWidth;
        animLeaf.classList.add("flip-to-left");

        setTimeout(() => {
            renderSpread(targetPage).then(() => {
                animLeaf.style.display = "none";
                animLeaf.classList.remove("flip-to-left");
                isFlipping = false;
            });
        }, 500);
    }

    // Flip Backward (Turning back to the Left)
    async function flipPrev() {
        if (isFlipping || !currentPdfDoc) return;
        if (activeRightPage === 1 && activeLeftPage === null) return;

        let targetPage;
        if (activeLeftPage === totalPages && activeRightPage === null) {
            targetPage = totalPages - 2;
            if (targetPage < 1) targetPage = 1;
        } else if (activeLeftPage === null || activeLeftPage <= 2) {
            targetPage = 1;
        } else {
            targetPage = activeLeftPage - 2;
            if (targetPage < 1) targetPage = 1;
        }

        isFlipping = true;
        renderSpread(targetPage).then(() => {
            isFlipping = false;
        });
    }

    // Navigation events
    if (nextBtn) nextBtn.addEventListener("click", flipNext);
    if (navNextBtn) navNextBtn.addEventListener("click", flipNext);
    if (prevBtn) prevBtn.addEventListener("click", flipPrev);
    if (navPrevBtn) navPrevBtn.addEventListener("click", flipPrev);

    if (leafRight) {
        leafRight.addEventListener("click", function () {
            const isAtEnd = (activeLeftPage === totalPages && activeRightPage === null);
            if (!isAtEnd) flipNext();
        });
    }
    if (leafLeft) {
        leafLeft.addEventListener("click", function () {
            const isAtStart = (activeRightPage === 1 && activeLeftPage === null);
            if (!isAtStart) flipPrev();
        });
    }

    // Slider scrubbing
    if (slider) {
        slider.addEventListener("input", function () {
            const val = parseInt(this.value, 10);
            renderSpread(val);
        });
    }

    // Zoom Controls
    if (zoomInBtn) {
        zoomInBtn.addEventListener("click", function () {
            currentZoom = Math.min(currentZoom + 0.15, 1.6);
            if (stage) stage.style.transform = `scale(${currentZoom})`;
        });
    }

    if (zoomOutBtn) {
        zoomOutBtn.addEventListener("click", function () {
            currentZoom = Math.max(currentZoom - 0.15, 0.7);
            if (stage) stage.style.transform = `scale(${currentZoom})`;
        });
    }

    // Fullscreen Toggle
    if (fullscreenBtn) {
        fullscreenBtn.addEventListener("click", function () {
            if (!document.fullscreenElement) {
                modal.requestFullscreen().catch(err => console.log(err));
            } else {
                document.exitFullscreen();
            }
        });
    }

    // Keyboard Shortcuts
    document.addEventListener("keydown", function (e) {
        if (!modal.classList.contains("is-open")) return;
        if (e.key === "Escape") closeFlipbook();
        if (e.key === "ArrowRight" || e.key === "PageDown") {
            const isAtEnd = (activeLeftPage === totalPages && activeRightPage === null);
            if (!isAtEnd) flipNext();
        }
        if (e.key === "ArrowLeft" || e.key === "PageUp") {
            const isAtStart = (activeRightPage === 1 && activeLeftPage === null);
            if (!isAtStart) flipPrev();
        }
    });
});



