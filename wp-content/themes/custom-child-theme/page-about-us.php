            const slideWidth = firstSlide.offsetWidth;
            const moveAmount = currentIndex * slideWidth;

            track.style.transform = `translateX(-${moveAmount}px)`;

            // Update counter
            if (counter) {
                const displayIndex = String(currentIndex + 1).padStart(2, "0");
                const displayTotal = String(totalSlides).padStart(2, "0");
                counter.textContent = `${displayIndex} / ${displayTotal}`;
            }

            // Update dots active state
            if (dotsContainer) {
                const dots = dotsContainer.querySelectorAll(".ukt-prog-dot");
                dots.forEach((dot, index) => {
                    dot.classList.toggle("active", index === currentIndex);
                });
            }
        }

        function goToSlide(index) {
            const visible = getVisibleSlides();
            const maxIndex = Math.max(0, totalSlides - visible);
            currentIndex = Math.max(0, Math.min(index, maxIndex));
            updateCarousel();
        }

        function nextSlide() {
            const visible = getVisibleSlides();
            const maxIndex = Math.max(0, totalSlides - visible);
            if (currentIndex < maxIndex) {
                currentIndex++;
            } else {
                currentIndex = 0; // loop back to first slide
            }
            updateCarousel();
        }

        function prevSlide() {
            const visible = getVisibleSlides();
            const maxIndex = Math.max(0, totalSlides - visible);
            if (currentIndex > 0) {
                currentIndex--;
            } else {
                currentIndex = maxIndex; // loop to last slide
            }
            updateCarousel();
        }

        // Auto-play Movement Controls
        function startAutoPlay() {
            stopAutoPlay();
            autoPlayTimer = setInterval(nextSlide, autoPlayInterval);
        }

        function stopAutoPlay() {
            if (autoPlayTimer) {
                clearInterval(autoPlayTimer);
                autoPlayTimer = null;
            }
        }

        function resetAutoPlay() {
            stopAutoPlay();
            startAutoPlay();
        }

        // Pause on hover, resume on leave
        if (carouselSection) {
            carouselSection.addEventListener("mouseenter", stopAutoPlay);
            carouselSection.addEventListener("mouseleave", startAutoPlay);
        }

        // Button Event Listeners
        if (nextBtn) nextBtn.addEventListener("click", () => {
            nextSlide();
            resetAutoPlay();
        });
        if (prevBtn) prevBtn.addEventListener("click", () => {
            prevSlide();
            resetAutoPlay();
        });

        // Touch Swipe Support
        viewport.addEventListener("touchstart", function (e) {
            stopAutoPlay();
            startX = e.touches[0].clientX;
            isDragging = true;
        }, { passive: true });

        viewport.addEventListener("touchend", function (e) {
            if (!isDragging) return;
            isDragging = false;
            const endX = e.changedTouches[0].clientX;
            const diff = endX - startX;

            if (diff < -40) {
                nextSlide();
            } else if (diff > 40) {
                prevSlide();
            }
            startAutoPlay();
        }, { passive: true });

        // Keyboard navigation
        viewport.setAttribute("tabindex", "0");
        viewport.addEventListener("keydown", function (e) {
            if (e.key === "ArrowRight") {
                nextSlide();
                resetAutoPlay();
            } else if (e.key === "ArrowLeft") {
                prevSlide();
                resetAutoPlay();
            }
        });

        // Recompute on window resize
        let resizeTimer;
        window.addEventListener("resize", function () {
            clearTimeout(resizeTimer);
            resizeTimer = setTimeout(() => {
                buildDots();
                updateCarousel();
            }, 100);
        });

        // Initial build & start movement
        buildDots();
        updateCarousel();
        startAutoPlay();
    });

    // =========================================================
    // INAUGURATION LANGUAGE TABS SLIDING PILL SWITCH
    // =========================================================
    document.addEventListener("DOMContentLoaded", function () {
        const switchContainer = document.getElementById("inaugLangSwitch");
        const glider = document.getElementById("inaugSwitchGlider");
        const tabs = document.querySelectorAll("#inaugLangTabs .nav-link");
        if (!switchContainer || !glider || !tabs.length) return;

        function updateGlider(activeTab) {
            if (!activeTab) return;
            const containerRect = switchContainer.getBoundingClientRect();
            const tabRect = activeTab.getBoundingClientRect();
            const leftOffset = tabRect.left - containerRect.left;
            const width = tabRect.width;

            glider.style.width = width + "px";
            glider.style.transform = "translateX(" + (leftOffset - 5) + "px)";
        }

        // Initial positioning after DOM render
        const activeTab = document.querySelector("#inaugLangTabs .nav-link.active") || tabs[0];
        updateGlider(activeTab);

        // Re-sync after all fonts/styles settle
        setTimeout(function () {
            const currentActive = document.querySelector("#inaugLangTabs .nav-link.active") || tabs[0];
            updateGlider(currentActive);
        }, 100);

        // Listen to Bootstrap tab events and click events for immediate sliding
        tabs.forEach(function (tab) {
            tab.addEventListener("shown.bs.tab", function (e) {
                updateGlider(e.target);
            });
            tab.addEventListener("click", function () {
                updateGlider(tab);
            });
        });

        // Re-adjust position on window resize
        window.addEventListener("resize", function () {
            const currentActive = document.querySelector("#inaugLangTabs .nav-link.active") || tabs[0];
            updateGlider(currentActive);
        });
    });
